                        '    seq_weights: str | None = None  # .npy [n_train]: a weight per train sequence '
                        '(pipeline/shift.py), times the row weights\n'
                        '    train_part: str = "all"     # all | head (output layer only) | top (output layer + last '
                        'GRU layer): the rest is frozen\n'
                        '    valid_frac: float = 1.0     # <1: train on this random share of the validation sequences '
                        '(bagging, for weight soups)\n'
                        '    bag_seed: int = 0           # which random share (valid_frac)\n'
                        '\n'
                        '\n'
                        '@dataclass\n'
                        'class Common:\n'
                        '    epochs: int = 4\n'
                        '    batch: int = 256            # sequences per batch\n'
                        '    chunk: int = 500            # TBPTT length\n'
                        '    clip_grad: float = 1.0\n'
                        '    train_seqs: int | None = None\n'
                        '    holdout: int = 500\n'
                        '    valid_seqs: int = 400\n'
                        '    evals_per_epoch: int = 2\n'
                        '    seed: int = 0               # data order + holdout split\n'
                        '    device: str = "auto"\n'
                        '    threads: int = 4            # parquet reader threads\n'
                        '    cache_eval: bool = False    # keep eval data in RAM (~9 MB per sequence)\n'
                        '    cache_train: bool = False   # keep training sequences in RAM after first read\n'
                        '    data_dir: str = "datasets"\n'
                        '    out_dir: str = "runs"\n'
                        '    teacher: str | None = None  # teacher predictions on train.parquet (.npy, [n_seqs, 20000, '
                        '2]) for distillation\n'
                        '    n_folds: int = 4            # for ExpConfig.fold\n'
                        '    row_weights: str | None = None  # p(scored) per train row (.npy [n_seqs, 20000]) for '
                        'ExpConfig.mask_weight\n'
                        '    valid_split: str | None = None  # split.json from mask_model: evaluate and select on '
                        'validation half B\n'
                        '    pool: str = "train"         # training stream: train | valid | train+valid (validation '
                        'sequences: ExpConfig.valid_part)\n'
                        '    teacher_valid: str | None = None  # teacher predictions on valid.parquet (.npy [1873, '
                        '20000, 2]), ExpConfig.valid_distill\n'
                        '    skip_final_eval: bool = False  # no full validation / holdout scoring at the end (export '
                        'only)\n'
                        '    pool_valid_seqs: int | None = None  # tests: only the first N sequences of each '
                        'validation half join the pool\n'
                        '    extra: dict = field(default_factory=dict)\n'
                        '\n'
                        '\n'
                        'class Experiment:\n'
                        '    def __init__(self, cfg: ExpConfig, common: Common, device, n_batches):\n'
                        '        self.cfg = cfg\n'
                        '        self.chunk = cfg.chunk or common.chunk\n'
                        '        self.epochs = cfg.epochs or common.epochs\n'
                        '        self.teacher_path = (cfg.teacher or common.teacher) if cfg.distill > 0 else None\n'
                        '        assert cfg.distill == 0 or self.teacher_path, f"{cfg.name}: distill > 0 needs a '
                        'teacher"\n'
                        '        self.micro = cfg.micro_batch or common.batch\n'
                        '        total_steps = (self.epochs * n_batches * math.ceil(common.batch / self.micro)  # '
                        'upper bound on steps\n'
                        '                       * math.ceil(20000 / self.chunk))\n'
                        '        self.kind = "act" if cfg.feats is True else (cfg.feats or None)\n'
                        '        n_extra = feat_width(self.kind)\n'
                        '        assert cfg.aux == 0 or cfg.arch == "gru", "auxiliary targets: GRU only"\n'
                        '        assert cfg.states is None or (cfg.arch == "gru" and not cfg.init_baseline), "state '
                        'head: plain GRU only"\n'
                        '        assert cfg.cls == 0 or cfg.states is not None, "cls needs a state head (states)"\n'
                        '        assert cfg.valid_part in (None, "A", "B", "all"), cfg.valid_part\n'
                        '        assert cfg.valid_part is None or ("valid" in common.pool and common.valid_split), \\\n'
                        '            f"{cfg.name}: valid_part needs --pool valid / train+valid and --valid-split"\n'
                        '        assert cfg.valid_part is None or not cfg.select, f"{cfg.name}: trained on validation '
                        '-> select=False"\n'
                        '        assert cfg.use_train and "train" in common.pool or cfg.valid_part, f"{cfg.name}: '
                        'nothing to train on"\n'
                        '        assert cfg.valid_distill == 0 or (cfg.distill > 0 and common.teacher_valid), '
                        '"valid_distill: distill + teacher_valid"\n'
                        '        assert cfg.swa_from is None or not cfg.select, "swa_from needs select=False"\n'
                        '        assert cfg.train_part in ("all", "head", "top"), cfg.train_part\n'
                        '        assert cfg.train_part == "all" or (cfg.init and cfg.arch == "gru"), f"{cfg.name}: '
                        'train_part needs a GRU init"\n'
                        '        assert 0 < cfg.valid_frac <= 1 and (cfg.valid_frac == 1 or cfg.valid_part), '
                        'f"{cfg.name}: valid_frac"\n'
                        '        torch.manual_seed(cfg.seed)\n'
                        '        if cfg.arch == "ggru":\n'
                        '            assert self.kind == "grp", "arch ggru takes the group probabilities: '
                        'feats=\'grp\'"\n'
                        '        if cfg.init_baseline:\n'
                        '            assert cfg.arch == "gru" and not cfg.diff and cfg.hidden == 128 and cfg.layers == '
                        '2, "baseline shape is fixed"\n'
                        '            self.net = load_baseline("baseline/baseline.onnx")\n'
                        '        elif cfg.arch == "gru":\n'
                        '            self.net = GRUNet(cfg.hidden, cfg.layers, cfg.diff, cfg.dropout, cfg.cell, '
                        'n_extra=n_extra,\n'
                        '                              feat_kind=self.kind, n_aux=N_AUX if cfg.aux > 0 else 0,\n'
                        '                              states=state_values(cfg.states) if cfg.states is not None else '
                        'None)\n'
                        '        else:\n'
                        '            self.net = build_net(dict(arch=cfg.arch, hidden=cfg.hidden, layers=cfg.layers, '
                        'use_diff=cfg.diff,\n'
                        '                                      dropout=cfg.dropout, n_extra=n_extra, '
                        'feat_kind=self.kind,\n'
                        '                                      **({"kernel": cfg.kernel} if cfg.arch == "tcn" else '
                        '{})))\n'
                        '        if cfg.init:\n'
                        '            ck = torch.load(cfg.init, map_location="cpu", weights_only=False)\n'
                        '            if cfg.arch == "ggru" and ck["config"].get("arch", "gru") == "gru":\n'
                        '                self.net.from_gru(ck["state_dict"])\n'
                        '            elif cfg.states is not None and "states" not in ck["config"]:  # new state head '
                        "on a plain model's body\n"
                        '                sd = {k: v for k, v in ck["state_dict"].items() if not '
                        'k.startswith("head.")}\n'
                        '                missing, unexpected = self.net.load_state_dict(sd, strict=False)\n'
                        '                assert not unexpected and all(k.startswith("head.") for k in missing), '
                        '(missing, unexpected)\n'
                        '            else:\n'
                        '                self.net.load_state_dict(ck["state_dict"])\n'
                        '        self.net.to(device)\n'
                        '        self.ema_net = copy.deepcopy(self.net) if cfg.ema > 0 else None\n'
                        '        self.n_updates = 0\n'
                        '        self.total_steps = total_steps\n'
                        '        if cfg.train_part != "all":  # freeze everything below the trained part\n'
                        '            top = f"_l{self.net.config[\'layers\'] - 1}"\n'
                        '            for n, p in self.net.named_parameters():\n'
                        '                p.requires_grad_(n.startswith("head.") or (cfg.train_part == "top" and '
                        'n.startswith("gru.")\n'
                        '                                                             and (n.endswith(top) or '
                        'n.endswith(top + "_reverse"))))\n'
                        '        trainable = [p for p in self.net.parameters() if p.requires_grad]\n'
                        '        self.n_trainable = sum(p.numel() for p in trainable)\n'
                        '        self.opt = torch.optim.AdamW(trainable, lr=cfg.lr, weight_decay=cfg.wd)\n'
                        '        self.in_bag = None  # valid_frac < 1: bool per validation sequence (set by '
                        'train_many)\n'
                        '        if cfg.sched == "const":\n'
                        '            self.sched = torch.optim.lr_scheduler.LambdaLR(self.opt, lambda step: 1.0)\n'
                        '        else:\n'
                        '            assert cfg.sched == "onecycle", cfg.sched\n'
                        '            self.sched = torch.optim.lr_scheduler.OneCycleLR(self.opt, max_lr=cfg.lr, '
                        'total_steps=total_steps,\n'
                        '                                                             pct_start=max(0.05, 3 / '
                        'total_steps))\n'
                        '        self.swa, self.n_swa = None, 0\n'
                        '        self.seq_w = None\n'
                        '        if cfg.seq_weights:\n'
                        '            self.seq_w = np.load(cfg.seq_weights).astype(np.float32)\n'
                        '            assert self.seq_w.ndim == 1 and (self.seq_w >= 0).all(), f"{cfg.seq_weights}: '
                        'shape {self.seq_w.shape}"\n'
                        '        self.dir = os.path.join(common.out_dir, cfg.name)\n'
                        '        os.makedirs(self.dir, exist_ok=True)\n'
                        '        self.log_f = open(os.path.join(self.dir, "log.jsonl"), "a")\n'
                        '        self.best = -1.0\n'
                        '        self.params = sum(p.numel() for p in self.net.parameters())\n'
                        '        self.cost = macs(self.net.config) / BASELINE_MACS\n'
                        '\n'
                        '    @property\n'
                        '    def eval_net(self):\n'
                        '        return self.ema_net if self.ema_net is not None else self.net\n'
                        '\n'
                        '    @torch.no_grad()\n'
                        '    def update_ema(self):\n'
                        '        self.n_updates += 1\n'
                        '        if self.ema_net is None:\n'
                        '            return\n'
                        '        decay = min(self.cfg.ema, (1 + self.n_updates) / (10 + self.n_updates))  # warm-up\n'
                        '        for pe, p in zip(self.ema_net.parameters(), self.net.parameters()):\n'
                        '            pe.lerp_(p, 1 - decay)\n'
                        '\n'
                        '    @torch.no_grad()\n'
                        '    def add_swa(self):\n'
                        '        sd = self.eval_net.state_dict()\n'
                        '        if self.swa is None:\n'
                        '            self.swa = {k: v.detach().cpu().double() if v.is_floating_point() else '
                        'v.detach().cpu().clone()\n'
                        '                        for k, v in sd.items()}  # float64 on the CPU (MPS has no float64)\n'
                        '        else:\n'
                        '            for k, v in sd.items():\n'
                        '                if v.is_floating_point():\n'
                        '                    self.swa[k] += v.detach().cpu().double()\n'
                        '        self.n_swa += 1\n'
                        '\n'
                        '    def save(self, n_folds):\n'
                        '        torch.save({"config": self.net.config, "state_dict": self.eval_net.state_dict(), '
                        '"exp": asdict(self.cfg),\n'
                        '                    "n_folds": n_folds}, os.path.join(self.dir, "best.pt"))\n'
                        '\n'
                        '    def log(self, **kw):\n'
                        '        line = json.dumps(kw)\n'
                        '        self.log_f.write(line + "\\n")\n'
                        '        self.log_f.flush()\n'
                        '        print(f"[{self.cfg.name}] {line}", flush=True)\n'
                        '\n'
                        '\n'
                        'def _store(common, name):\n'
                        '    return SeqStore(os.path.join(common.data_dir, f"{name}.parquet"), '
                        'n_threads=common.threads)\n'
                        '\n'
                        '\n'
                        'def train_many(configs: list[ExpConfig], common: Common):\n'
                        '    from .fast_eval import pick_device\n'
                        '\n'
                        '    device = pick_device(common.device)\n'
                        '    if device.type == "cuda":\n'
                        '        torch.backends.cudnn.benchmark = True\n'
                        '    rng = np.random.default_rng(common.seed)\n'
                        '    train, valid = _store(common, "train"), _store(common, "valid")\n'
                        '    assert common.pool in ("train", "valid", "train+valid"), common.pool\n'
                        '    pool = PoolStore(train, _store(common, "valid")) if "valid" in common.pool else train\n'
                        '    if common.cache_train:\n'
                        '        train.enable_cache()\n'
                        '    if common.cache_eval:\n'
                        '        valid.enable_cache()\n'
                        '    train_ids, hold_ids = split_train(train.n_seqs, common.holdout, common.seed)\n'
                        '    if common.train_seqs:\n'
                        '        train_ids = rng.choice(train_ids, common.train_seqs, replace=False)\n'
                        '    split = json.load(open(common.valid_split)) if common.valid_split else None\n'
                        '    valid_B = split["B"] if split else None\n'
                        '    valid_A = split["A"] if split else None\n'
                        '    valid_ids = (valid_B or list(range(valid.n_seqs)))[:common.valid_seqs]\n'
                        '    pool_ids = list(train_ids) if "train" in common.pool else []\n'
                        '    if "valid" in common.pool:\n'
                        '        reps = max([c.valid_repeat for c in configs if c.valid_part] or [1])\n'
                        '        vs = sorted(valid_A[:common.pool_valid_seqs] + valid_B[:common.pool_valid_seqs])  # '
                        'halves A + B = all of valid\n'
                        '        pool_ids += [valid_key(v, c) for c in range(reps) for v in vs]\n'
                        '        half_of = {v: "A" for v in valid_A}\n'
                        '        half_of.update({v: "B" for v in valid_B})\n'
                        '        mtab = pq.read_table(os.path.join(common.data_dir, "valid_mask.parquet"), '
                        'columns=["step_in_seq", "is_scored"])\n'
                        '        need = mtab["step_in_seq"].to_numpy() >= WARMUP\n'
                        '        scored_share = float(mtab["is_scored"].to_numpy()[need].astype(np.float64).mean())  # '
                        'of the required rows\n'
                        '        print(f"pool {common.pool}: {len(pool_ids)} sequence passes per epoch; validation '
                        'scored share {scored_share:.4f}",\n'
                        '              flush=True)\n'
                        '    hold_store = train\n'
                        '    if common.cache_eval and not common.cache_train:  # cache holdout without caching all of '
                        'train\n'
                        '        hold_store = _store(common, "train")\n'
                        '        hold_store.enable_cache()\n'
                        '\n'
                        '    n_batches = math.ceil(len(pool_ids) / common.batch)\n'
                        '    exps = [Experiment(c, common, device, n_batches) for c in configs]\n'
                        '    for e in exps:\n'
                        '        if e.cfg.valid_frac < 1:\n'
                        '            e.in_bag = np.random.default_rng(10_000 + e.cfg.bag_seed).random(valid.n_seqs) < '
                        'e.cfg.valid_frac\n'
                        '    teachers = {}  # path -> memmap, loaded once and shared by the models that use it\n'
                        '    for path in sorted({e.teacher_path for e in exps if e.teacher_path}):\n'
                        '        teachers[path] = np.load(path, mmap_mode="r")\n'
                        '        assert teachers[path].shape[:2] == (train.n_seqs, 20000), f"teacher {path}: shape '
                        '{teachers[path].shape}"\n'
                        '    teacher_valid = None\n'
                        '    if any(e.cfg.valid_distill > 0 for e in exps):\n'
                        '        teacher_valid = np.load(common.teacher_valid, mmap_mode="r")\n'
                        '        assert teacher_valid.shape[:2] == (valid.n_seqs, 20000), f"teacher_valid: shape '
                        '{teacher_valid.shape}"\n'
                        '    row_w, p_norm = None, {}\n'
                        '    if any(e.cfg.mask_weight > 0 for e in exps):\n'
                        '        assert common.row_weights, "mask_weight > 0 needs --row-weights (see '
                        'pipeline/mask_model.py)"\n'
                        '        row_w = np.load(common.row_weights, mmap_mode="r")\n'
                        '        assert row_w.shape == (train.n_seqs, 20000), f"row weights shape {row_w.shape}"\n'
                        '        sample = np.asarray(row_w[np.sort(np.asarray(train_ids))[::20], 99:], '
                        'dtype=np.float32)  # train rows only\n'
                        '        for pw in {e.cfg.mask_power for e in exps if e.cfg.mask_weight > 0}:\n'
                        '            p_norm[pw] = float((sample ** pw).mean())  # so the average row weight stays '
                        'about 1\n'
                        '            print(f"row weights: mean p^{pw:g} = {p_norm[pw]:.4f}", flush=True)\n'
                        '    n_epochs = max(e.epochs for e in exps)\n'
                        '    t0 = time.time()\n'
                        '    for e in exps:\n'
                        '        e.log(event="start", config=asdict(e.cfg), common=asdict(common), device=str(device), '
                        'params=e.params,\n'
                        '              cost=round(e.cost, 3), train_seqs=len(train_ids), holdout=len(hold_ids), '
                        'steps=e.total_steps,\n'
                        '              trainable=e.n_trainable, bag=int(e.in_bag.sum()) if e.in_bag is not None else '
                        'None,\n'
                        '              pool=common.pool, pool_seqs=len(pool_ids))\n'
                        '    eval_at = set(np.linspace(0, n_batches, common.evals_per_epoch + 1, dtype=int)[1:] - 1)\n'
                        '\n'
                        '    def run_eval(epoch, bi, group):\n'
                        '        nets = [e.eval_net for e in group]\n'
                        '        vs = evaluate_many(nets, valid, valid_ids, device)\n'
                        '        hs = evaluate_many(nets, hold_store, hold_ids, device)\n'
                        '        for e, v, h in zip(group, vs, hs):\n'
                        "            # with a valid split: select on half B's scored rows (the mask model never saw "
                        'them);\n'
                        "            # otherwise don't select on the visible valid mask alone\n"
                        '            sel = v["scored"] if valid_B else (v["scored"] + h["all"]) / 2\n'
                        '            if e.cfg.group is not None and v[f"scored_g{e.cfg.group}"] == '
                        'v[f"scored_g{e.cfg.group}"]:\n'
                        '                sel = v[f"scored_g{e.cfg.group}"]  # a group model is selected on its '
                        "group's rows (if any)\n"
                        '            is_best = e.cfg.select and sel > e.best\n'
                        '            if is_best:\n'
                        '                e.best = sel\n'
                        '                e.save(common.n_folds)\n'
                        '            e.log(event="eval", epoch=epoch, batch=bi, valid=round(v["scored"], 6), '
                        'valid_all=round(v["all"], 6),\n'
                        '                  valid_groups=[round(v[f"scored_g{g}"], 4) for g in range(4)],\n'
                        '                  holdout=round(h["all"], 6), select=round(sel, 6), best=is_best, '
                        'time=round(time.time() - t0, 1))\n'
                        '            e.net.train()\n'
                        '\n'
                        '    for epoch in range(n_epochs):\n'
                        '        active = [e for e in exps if epoch < e.epochs]\n'
                        '        for e in active:\n'
                        '            e.net.train()\n'
                        '        ids = np.asarray(rng.permutation(np.asarray(pool_ids, np.int64)))\n'
                        '        for bi, (X, Y, M) in enumerate(pool.batches(list(ids), common.batch)):\n'
                        '            tb = time.time()\n'
                        '            batch_ids = ids[bi * common.batch:(bi + 1) * common.batch]\n'
                        '            groups = group_label(Y)\n'
                        '            is_tr = batch_ids < VOFF\n'
                        '            vseq = batch_ids % VOFF  # validation sequence of a validation key\n'
                        '            vcopy = batch_ids // VOFF - 1\n'
                        '            vhalf = np.array([half_of[v] if not t else "" for v, t in zip(vseq, is_tr)]) if '
                        'not is_tr.all() else None\n'
                        '            Xd = torch.from_numpy(X).to(device, non_blocking=True)  # one host->device copy '
                        'per batch\n'
                        '            # extras once per batch and kind, shared by every model of that kind, joined on '
                        'the GPU (the joined\n'
                        '            # 256-seq batch would be another 3+ GB array in host RAM)\n'
                        '            Xk = {None: Xd, **{k: torch.cat([Xd, torch.from_numpy(extra_features(X, '
                        'k)).to(device)], -1)\n'
                        '                               for k in sorted({e.kind for e in active} - {None})}}\n'
                        '            Ad = Vd = None\n'
                        '            if any(e.cfg.aux > 0 for e in active):\n'
                        '                Ad, Vd = aux_targets(Xd)\n'
                        '            Yd = torch.from_numpy(Y).to(device, non_blocking=True)\n'
                        '            def per_train_seq(arr):  # rows of a train-indexed array for this batch (0 for '
                        'validation sequences)\n'
                        '                out = np.zeros((len(batch_ids),) + arr.shape[1:], np.float32)\n'
                        '                if is_tr.any():\n'
                        '                    out[is_tr] = take_rows(arr, batch_ids[is_tr])\n'
                        '                return torch.from_numpy(out).to(device)\n'
                        '            Td = {path: per_train_seq(t) for path, t in teachers.items() if '
                        'any(e.teacher_path == path for e in active)}\n'
                        '            Pd = None\n'
                        '            if row_w is not None and any(e.cfg.mask_weight > 0 for e in active):\n'
                        '                Pd = per_train_seq(row_w)\n'
                        '            Md = TVd = None\n'
                        '            if vhalf is not None:\n'
                        '                Md = torch.from_numpy(M).to(device)\n'
                        '                if teacher_valid is not None and any(e.cfg.valid_distill > 0 for e in '
                        'active):\n'
                        '                    tv = np.zeros((len(batch_ids), 20000, 2), np.float32)\n'
                        '                    tv[~is_tr] = take_rows(teacher_valid, vseq[~is_tr])\n'
                        '                    TVd = torch.from_numpy(tv).to(device)\n'
                        '            for e in active:\n'
                        '                Xe, Ye, Te = Xk[e.kind], Yd, Td.get(e.teacher_path)\n'
                        '                Ae, Ve = (Ad, Vd) if e.cfg.aux > 0 else (None, None)\n'
                        '                We = None\n'
                        '                if e.cfg.mask_weight > 0:\n'
                        '                    lam, pw = e.cfg.mask_weight, e.cfg.mask_power\n'
                        '                    We = (1 - lam) + lam * Pd.clamp(min=0) ** pw / p_norm[pw]\n'
                        '                keep = is_tr.copy() if e.cfg.use_train else np.zeros(len(batch_ids), bool)\n'
                        "                if e.cfg.fold is not None:  # out-of-fold model: drop its fold's sequences "
                        'from the batch\n'
                        '                    keep &= ~is_tr | (batch_ids % common.n_folds != e.cfg.fold)\n'
                        '                if e.cfg.valid_part and vhalf is not None:  # its validation sequences (and '
                        'copies)\n'
                        '                    mine = ~is_tr & (vcopy < e.cfg.valid_repeat) & ((vhalf == '
                        'e.cfg.valid_part) | (e.cfg.valid_part == "all"))\n'
                        "                    if e.in_bag is not None:  # bagging: only this model's share of the "
                        'validation sequences\n'
                        '                        mine[~is_tr] &= e.in_bag[vseq[~is_tr]]\n'
                        '                    keep |= mine\n'
                        '                vrows = ~is_tr & keep\n'
                        '                if vrows.any():  # validation rows: true-mask weights; teacher target blended '
                        'with the labels\n'
                        '                    u = e.cfg.unscored_weight\n'
                        '                    wv = (Md.float() + u * (~Md).float()) / (scored_share + u * (1 - '
                        'scored_share))\n'
                        '                    vr = torch.as_tensor(np.flatnonzero(vrows), device=device)\n'
                        '                    We = torch.ones_like(Md, dtype=torch.float32) if We is None else '
                        'We.clone()\n'
                        '                    We[vr] = wv[vr]\n'
                        '                    if Te is not None:\n'
                        '                        v = e.cfg.valid_distill\n'
                        '                        tv = Yd[vr].clamp(-CLIP, CLIP) if v == 0 else (1 - v) * '
