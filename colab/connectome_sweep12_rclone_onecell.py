                      '    def forward(self, x, h=None, x_prev=None):\n'
                      '        """x [B,T,112 (+ extras)]; h list of [B,H] per layer or None; x_prev as in GRUNet."""\n'
                      '        z = _model_inputs(x, x_prev, self.use_diff, self.n_extra)\n'
                      '        new = []\n'
                      '        for l, proj in enumerate(self.proj):\n'
                      '            k, c = proj(z).chunk(2, -1)\n'
                      '            z = self._scan(k, c, None if h is None else h[l])\n'
                      '            new.append(z[:, -1])\n'
                      '            if l < len(self.proj) - 1:\n'
                      '                z = self.drop(z)\n'
                      '        return self.head(z), new\n'
                      '\n'
                      '    def stream_states(self):\n'
                      '        return [(f"h{l}", (1, self.hidden)) for l in range(len(self.proj))]\n'
                      '\n'
                      '    def stream_step(self, z, states):\n'
                      '        """One row: z [1,1,in] (already built inputs), states list of [1,H] -> (pred [1,1,2], '
                      'new states)."""\n'
                      '        z, new = z[:, 0], []\n'
                      '        for proj, h in zip(self.proj, states):\n'
                      '            k, c = proj(z).chunk(2, -1)\n'
                      '            z = h + torch.sigmoid(k) * (_g(c) - h)\n'
                      '            new.append(z)\n'
                      '        return self.head(z)[:, None], new\n'
                      '\n'
                      '\n'
                      'class TCNNet(nn.Module):\n'
                      '    """Causal dilated temporal convolution network (Bai et al. 2018, WaveNet-style) + linear '
                      'head.\n'
                      '\n'
                      '    Input projection to `hidden` channels, then `layers` pre-norm residual blocks\n'
                      '    z <- z + W_mix relu(conv_{kernel, dilation}(LayerNorm(z))), dilation = kernel**l, so the '
                      'receptive field\n'
                      '    is kernel**layers rows (2**11 = 2048, 3**7 = 2187). Each output sees a fixed window of past '
                      'rows; unlike an\n'
                      '    RNN nothing older can leak in. State between chunks: the last (kernel - 1) * dilation '
                      'normalised inputs of\n'
                      '    each block ([B, pad_l, C]), zeros before the sequence start, so chunked training, '
                      'evaluation and row-by-row\n'
                      '    inference see exactly the same context."""\n'
                      '\n'
                      '    def __init__(self, hidden=64, layers=11, use_diff=False, dropout=0.0, n_extra=0, kernel=2, '
                      'feat_kind=None):\n'
                      '        super().__init__()\n'
                      '        assert kernel >= 2, "TCN kernel must be >= 2"\n'
                      '        self.config = dict(arch="tcn", hidden=hidden, layers=layers, use_diff=use_diff, '
                      'dropout=dropout,\n'
                      '                           n_extra=n_extra, kernel=kernel, **({"feat_kind": feat_kind} if '
                      'feat_kind else {}))\n'
                      '        self.use_diff, self.n_extra, self.hidden, self.kernel = use_diff, n_extra, hidden, '
                      'kernel\n'
                      '        self.feat_kind = feat_kind or (kind_for_width(n_extra) if n_extra else None)\n'
                      '        self.dilations = [kernel ** l for l in range(layers)]\n'
                      '        self.pads = [(kernel - 1) * d for d in self.dilations]\n'
                      '        in_dim = N_FEATURES * (2 if use_diff else 1) + n_extra\n'
                      '        self.inp = nn.Linear(in_dim, hidden)\n'
                      '        self.norms = nn.ModuleList([nn.LayerNorm(hidden) for _ in range(layers)])\n'
                      '        self.convs = nn.ModuleList([nn.Conv1d(hidden, hidden, kernel, dilation=d) for d in '
                      'self.dilations])\n'
                      '        self.mix = nn.ModuleList([nn.Linear(hidden, hidden) for _ in range(layers)])\n'
                      '        self.drop = nn.Dropout(dropout)\n'
                      '        self.out_norm = nn.LayerNorm(hidden)\n'
                      '        self.head = nn.Linear(hidden, 2)\n'
                      '\n'
                      '    @property\n'
                      '    def receptive_field(self):\n'
                      '        return 1 + sum(self.pads)\n'
                      '\n'
                      '    def forward(self, x, h=None, x_prev=None):\n'
                      '        """x [B,T,112 (+ extras)]; h list of [B, pad_l, C] per block or None; x_prev as in '
                      'GRUNet."""\n'
                      '        z = self.inp(_model_inputs(x, x_prev, self.use_diff, self.n_extra))\n'
                      '        B, new = z.shape[0], []\n'
                      '        for l, (norm, conv, mix, pad) in enumerate(zip(self.norms, self.convs, self.mix, '
                      'self.pads)):\n'
                      '            u = norm(z)\n'
                      '            past = h[l] if h is not None else u.new_zeros(B, pad, u.shape[-1])\n'
                      '            full = torch.cat([past, u], 1)  # [B, pad + T, C]\n'
                      '            new.append(full[:, -pad:])\n'
                      '            y = conv(full.transpose(1, 2)).transpose(1, 2)  # [B, T, C]\n'
                      '            z = z + mix(self.drop(F.relu(y)))\n'
                      '        return self.head(self.out_norm(z)), new\n'
                      '\n'
                      '    def stream_states(self):\n'
                      '        return [(f"b{l}", (1, pad, self.hidden)) for l, pad in enumerate(self.pads)]\n'
                      '\n'
                      '    def stream_step(self, z, states):\n'
                      '        """One row: z [1,1,in], states list of [1, pad_l, C] -> (pred [1,1,2], new states). '
                      'Buffers are shifted\n'
                      '        with Concat + Slice (simple, but copies every buffer once per row: see the notes on '
                      'ring buffers)."""\n'
                      '        z, new = self.inp(z), []\n'
                      '        for norm, conv, mix, d, buf in zip(self.norms, self.convs, self.mix, self.dilations, '
                      'states):\n'
                      '            full = torch.cat([buf, norm(z)], 1)  # [1, pad + 1, C]\n'
                      '            new.append(full[:, 1:])\n'
                      "            taps = full[:, ::d]  # the kernel's inputs: rows t - (k-1)d, ..., t - d, t\n"
                      '            y = F.conv1d(taps.transpose(1, 2), conv.weight, conv.bias).transpose(1, 2)  # [1, '
                      '1, C]\n'
                      '            z = z + mix(F.relu(y))\n'
                      '        return self.head(self.out_norm(z)), new\n'
                      '\n'
                      '\n'
                      'class GroupGRUNet(nn.Module):\n'
                      '    """GRU conditioned on the instrument group. Input: the 112 features + the 4 detector '
                      'probabilities g\n'
                      '    (feature kind "grp"). The probabilities rescale and shift every input (FiLM: x * (1 + g '
                      'G_scale) + g G_shift)\n'
                      '    and mix 4 output heads (pred = sum_k g_k head_k(h)). G_scale / G_shift start at zero and '
                      'all heads equal, so\n'
                      '    `from_gru` gives exactly the plain GRU it starts from. The GRU layers are kept separate '
                      '(one state per layer,\n'
                      '    as in the exported plain GRU)."""\n'
                      '    N_GROUPS = 4\n'
                      '\n'
                      '    def __init__(self, hidden=128, layers=2, dropout=0.0, n_extra=4, feat_kind="grp", '
                      'use_diff=False):\n'
                      '        super().__init__()\n'
                      '        assert n_extra == self.N_GROUPS and feat_kind == "grp" and not use_diff\n'
                      '        self.config = dict(arch="ggru", hidden=hidden, layers=layers, dropout=dropout, '
                      'n_extra=n_extra,\n'
                      '                           feat_kind=feat_kind, use_diff=False)\n'
                      '        self.use_diff, self.n_extra, self.feat_kind, self.hidden = False, n_extra, feat_kind, '
                      'hidden\n'
                      '        self.film_scale = nn.Parameter(torch.zeros(self.N_GROUPS, N_FEATURES))\n'
                      '        self.film_shift = nn.Parameter(torch.zeros(self.N_GROUPS, N_FEATURES))\n'
                      '        self.layers = nn.ModuleList([nn.GRU(N_FEATURES if l == 0 else hidden, hidden, 1, '
                      'batch_first=True)\n'
                      '                                     for l in range(layers)])\n'
                      '        self.drop = nn.Dropout(dropout)\n'
                      '        self.heads = nn.Linear(hidden, 2 * self.N_GROUPS)\n'
                      '\n'
                      '    @torch.no_grad()\n'
                      '    def from_gru(self, gru_state):\n'
                      '        """Copy a plain GRUNet\'s weights (same hidden / layers, no extras): the result '
                      'predicts exactly the same."""\n'
                      '        for l, layer in enumerate(self.layers):\n'
                      '            for n in ("weight_ih", "weight_hh", "bias_ih", "bias_hh"):\n'
                      '                getattr(layer, f"{n}_l0").copy_(gru_state[f"gru.{n}_l{l}"])\n'
                      '        self.heads.weight.copy_(gru_state["head.weight"].repeat(self.N_GROUPS, 1))\n'
                      '        self.heads.bias.copy_(gru_state["head.bias"].repeat(self.N_GROUPS))\n'
                      '        return self\n'
                      '\n'
                      '    def _mix(self, out, g):\n'
                      '        heads = self.heads(out).unflatten(-1, (self.N_GROUPS, 2))  # [..., 4, 2]\n'
                      '        return (heads * g.unsqueeze(-1)).sum(-2)\n'
                      '\n'
                      '    def _film(self, x):\n'
                      '        base, g = x[..., :N_FEATURES], x[..., N_FEATURES:N_FEATURES + self.N_GROUPS]\n'
                      '        return base * (1 + g @ self.film_scale) + g @ self.film_shift, g\n'
                      '\n'
                      '    def forward(self, x, h=None, x_prev=None):\n'
                      '        z, g = self._film(x)\n'
                      '        h = h if h is not None else [None] * len(self.layers)\n'
                      '        new = []\n'
                      '        for l, layer in enumerate(self.layers):\n'
                      '            z, hl = layer(self.drop(z) if l else z, h[l])\n'
                      '            new.append(hl)\n'
                      '        return self._mix(z, g), new\n'
                      '\n'
                      '    def stream_states(self):\n'
                      '        return [(f"h{l}", (1, 1, self.hidden)) for l in range(len(self.layers))]\n'
                      '\n'
                      '    def stream_step(self, x, states):\n'
                      '        z, g = self._film(x)\n'
                      '        new = []\n'
                      '        for layer, hl in zip(self.layers, states):\n'
                      '            z, hn = layer(z, hl)\n'
                      '            new.append(hn)\n'
                      '        return self._mix(z, g), new\n'
                      '\n'
                      '\n'
                      'ARCHS = {"gru": GRUNet, "mingru": MinGRUNet, "tcn": TCNNet, "ggru": GroupGRUNet}\n'
                      '\n'
                      '\n'
                      'def build_net(config):\n'
                      '    """Model from a saved config. GRU/LSTM configs predate the `arch` key, so it defaults to '
                      'gru."""\n'
                      '    cfg = dict(config)\n'
                      '    return ARCHS[cfg.pop("arch", "gru")](**cfg)\n'
                      '\n'
                      '\n'
                      'def needs_extra(net):\n'
                      '    members = list(net.nets) if isinstance(net, EnsembleNet) else [net]\n'
                      '    return max(getattr(m, "n_extra", 0) for m in members)\n'
                      '\n'
                      '\n'
                      'def feat_kind(net):\n'
                      '    """The feature kind a model (or every member of an ensemble) takes as extra inputs; None = '
                      'plain 112."""\n'
                      '    members = list(net.nets) if isinstance(net, EnsembleNet) else [net]\n'
                      '    kinds = {getattr(m, "feat_kind", None) for m in members}\n'
                      '    assert len(kinds - {None}) <= 1, f"members use different feature kinds: {kinds}"\n'
                      '    return max(kinds - {None}, default=None)\n'
                      '\n'
                      '\n'
                      'def detach_state(h):\n'
                      '    """Detach a recurrent state: tensor (GRU), (h, c) tuple (LSTM) or list of those '
                      '(ensemble)."""\n'
                      '    if isinstance(h, torch.Tensor):\n'
                      '        return h.detach()\n'
                      '    return type(h)(detach_state(x) for x in h)\n'
                      '\n'
                      '\n'
                      'def macs(config) -> int:\n'
                      '    """Multiply-adds per row (inference cost model). Ensembles: sum over members."""\n'
                      '    if "members" in config:\n'
                      '        return sum(macs(m) for m in config["members"])\n'
                      '    arch = config.get("arch", "gru")\n'
                      '    H, n_in = config["hidden"], N_FEATURES * (2 if config["use_diff"] else 1) + '
                      'config.get("n_extra", 0)\n'
                      '    if arch == "mingru":  # one [in -> 2H] projection per layer\n'
                      '        return sum(2 * H * (n_in if l == 0 else H) for l in range(config["layers"])) + 2 * H\n'
                      '    if arch == "tcn":  # input projection, per block a k-tap conv + 1x1 mix (LayerNorms '
                      'ignored)\n'
                      '        return n_in * H + config["layers"] * (config["kernel"] + 1) * H * H + 2 * H\n'
                      '    gates = 4 if config.get("cell", "gru") == "lstm" else 3\n'
                      '    total = 0\n'
                      '    if arch == "ggru":  # FiLM (2 x 4 x 112) + 4 heads on top of a plain GRU on the 112 inputs\n'
                      '        n_in = N_FEATURES\n'
                      '        total = 2 * 4 * N_FEATURES + 6 * H\n'
                      '    for _ in range(config["layers"]):\n'
                      '        total += gates * H * (n_in + H)\n'
                      '        n_in = H\n'
                      '    return total + (len(config["states"]) * (H + 4) if config.get("states") else 2 * H)\n'
                      '\n'
                      '\n'
                      'BASELINE_MACS = macs(dict(hidden=128, layers=2, use_diff=False))  # 190,720\n'
                      '\n'
                      '\n'
                      'def _rw(w, rw):\n'
                      '    """Multiply metric weights [N,2] by optional per-row weights [N]."""\n'
                      '    return w if rw is None else w * rw[:, None]\n'
                      '\n'
                      '\n'
                      'def wmse_loss(p, y, rw=None):\n'
                      '    """Weighted MSE with the metric\'s clipping and |y| weights (times optional row weights). '
                      'p, y: [N, 2]."""\n'
                      '    y = y.clamp(-CLIP, CLIP)\n'
                      '    w = _rw(y.abs(), rw)\n'
                      '    return ((w * (p - y) ** 2).sum(0) / (w.sum(0) + 1e-8)).mean()\n'
                      '\n'
                      '\n'
                      'def distill_loss(p, teacher, y, weight="y", rw=None):\n'
                      '    """MSE to the teacher\'s predictions. Row weights: "y" = |clipped target| (like the '
                      'metric),\n'
                      '    "none" = uniform, "teacher" = |teacher prediction| (no dependence on the noisy target)."""\n'
                      '    if weight == "y":\n'
                      '        w = y.clamp(-CLIP, CLIP).abs()\n'
                      '    elif weight == "teacher":\n'
                      '        w = teacher.abs()\n'
                      '    elif weight == "none":\n'
                      '        w = torch.ones_like(teacher)\n'
                      '    else:\n'
                      '        raise ValueError(weight)\n'
                      '    w = _rw(w, rw)\n'
                      '    return ((w * (p - teacher) ** 2).sum(0) / (w.sum(0) + 1e-8)).mean()\n'
                      '\n'
                      '\n'
                      'def wpearson(p, y, rw=None):\n'
                      '    """Per-target weighted Pearson (pooled over the rows given), metric conventions. -> '
                      '[2]."""\n'
                      '    y = y.clamp(-CLIP, CLIP)\n'
                      '    w = _rw(y.abs(), rw)\n'
                      '    W = w.sum(0) + 1e-8\n'
                      '    yc = y - (w * y).sum(0) / W\n'
                      '    pc = p - (w * p).sum(0) / W\n'
                      '    cov = (w * yc * pc).sum(0)\n'
                      '    return cov / torch.sqrt((w * yc * yc).sum(0) * (w * pc * pc).sum(0) + 1e-12)\n'
                      '\n'
                      '\n'
                      'def compute_loss(kind, p, y, alpha=0.1, rw=None):\n'
                      '    if kind == "wmse":\n'
                      '        return wmse_loss(p, y, rw)\n'
                      '    if kind == "pearson":\n'
                      '        return 1 - wpearson(p, y, rw).mean()\n'
                      '    if kind == "mix":  # correlation objective, small wmse term anchors the scale for clipping\n'
                      '        return 1 - wpearson(p, y, rw).mean() + alpha * wmse_loss(p, y, rw)\n'
                      '    raise ValueError(kind)\n'
                      '\n'
                      '\n'
                      'class EnsembleNet(nn.Module):\n'
                      '    """Average of several GRUNets. Each member\'s output is multiplied by `scales[k]` (per '
                      'target)\n'
                      '    first, so members with different prediction spreads count equally. h is a list, one per '
                      'member."""\n'
                      '\n'
                      '    def __init__(self, nets, scales):\n'
                      '        super().__init__()\n'
                      '        self.nets = nn.ModuleList(nets)\n'
                      '        self.register_buffer("scales", torch.as_tensor(np.asarray(scales), '
                      'dtype=torch.float32))  # [K, 2]\n'
                      '        self.use_diff = any(n.use_diff for n in nets)\n'
                      '        self.config = {"members": [n.config for n in nets], "scales": '
                      'np.asarray(scales).tolist()}\n'
                      '\n'
                      '    def forward(self, x, h=None, x_prev=None):\n'
                      '        h = h if h is not None else [None] * len(self.nets)\n'
                      '        preds, new_h = [], []\n'
                      '        for k, (net, hk) in enumerate(zip(self.nets, h)):\n'
                      '            p, hn = net(x, hk, x_prev if net.use_diff else None)\n'
                      '            preds.append(p * self.scales[k])\n'
                      '            new_h.append(hn)\n'
                      '        return torch.stack(preds).mean(0), new_h\n'
                      '\n'
                      '\n'
                      'def _split_layers(net):\n'
                      '    """Single-layer copies of a stacked GRU/LSTM, so the ONNX graph gets one state input per '
                      'layer\n'
                      '    (as in the baseline) instead of slicing/concatenating a stacked state on every row."""\n'
                      '    rnn, mods = net.gru, []\n'
                      '    for l in range(rnn.num_layers):\n'
                      '        m = type(rnn)(rnn.input_size if l == 0 else rnn.hidden_size, rnn.hidden_size, 1, '
                      'batch_first=True)\n'
                      '        for n in ("weight_ih", "weight_hh", "bias_ih", "bias_hh"):\n'
                      '            getattr(m, f"{n}_l0").data.copy_(getattr(rnn, f"{n}_l{l}").data)\n'
                      '        mods.append(m)\n'
                      '    return nn.ModuleList(mods)\n'
                      '\n'
                      '\n'
                      'def _member_states(m):\n'
                      '    """(name suffix, shape) of each streaming state of one model, in graph order."""\n'
                      '    if isinstance(m, GRUNet):\n'
                      '        H, lstm = m.config["hidden"], m.cell == "lstm"\n'
                      '        return [s for l in range(m.config["layers"])\n'
                      '                for s in [(f"h{l}", (1, 1, H))] + ([(f"c{l}", (1, 1, H))] if lstm else [])]\n'
                      '    return m.stream_states()\n'
                      '\n'
                      '\n'
                      'class _Step(nn.Module):\n'
                      '    """One-row step graph: (x [1,1,112], x_prev [1,112], *states) -> (pred [1,1,2], *new '
                      'states).\n'
                      '    States are flat, per member: GRU one h [1,1,H] per layer, LSTM h and c per layer, minGRU '
                      'one h [1,H] per\n'
                      '    layer, TCN one input buffer [1, pad, C] per block."""\n'
                      '\n'
                      '    def __init__(self, net):\n'
                      '        super().__init__()\n'
                      '        self.ensemble = isinstance(net, EnsembleNet)\n'
                      '        members = list(net.nets) if self.ensemble else [net]\n'
                      '        self.rnn = [isinstance(m, GRUNet) for m in members]\n'
                      '        self.layers = nn.ModuleList([_split_layers(m) if r else nn.ModuleList() for m, r in '
                      'zip(members, self.rnn)])\n'
                      '        self.heads = nn.ModuleList([m.head if r else nn.Identity() for m, r in zip(members, '
                      'self.rnn)])\n'
                      '        self.streams = nn.ModuleList([nn.Identity() if r else m for m, r in zip(members, '
                      'self.rnn)])\n'
                      '        self.n_states = [len(_member_states(m)) for m in members]\n'
                      '        self.diff = [m.use_diff for m in members]\n'
                      '        self.n_extra = [getattr(m, "n_extra", 0) for m in members]\n'
                      '        self.lstm = [r and m.cell == "lstm" for m, r in zip(members, self.rnn)]\n'
                      '        self.register_buffer("scales", net.scales if self.ensemble else torch.ones(1, 2))\n'
                      '\n'
                      '    def forward(self, x, x_prev, *states):\n'
                      '        states, new, preds, i = list(states), [], [], 0\n'
                      '        for k, layers in enumerate(self.layers):\n'
                      '            base = x[..., :N_FEATURES]\n'
                      '            parts = [base] + ([base - x_prev[:, None]] if self.diff[k] else []) + \\\n'
                      '                    ([x[..., N_FEATURES:N_FEATURES + self.n_extra[k]]] if self.n_extra[k] else '
                      '[])\n'
                      '            z = torch.cat(parts, -1) if len(parts) > 1 else base\n'
                      "            if not self.rnn[k]:  # minGRU / TCN: the model's own one-row update\n"
                      '                p, ns = self.streams[k].stream_step(z, states[i:i + self.n_states[k]])\n'
                      '                new += ns\n'
                      '                i += self.n_states[k]\n'
                      '            else:\n'
                      '                for layer in layers:\n'
                      '                    if self.lstm[k]:\n'
                      '                        z, (h, c) = layer(z, (states[i], states[i + 1]))\n'
                      '                        new += [h, c]\n'
                      '                        i += 2\n'
                      '                    else:\n'
                      '                        z, h = layer(z, states[i])\n'
                      '                        new.append(h)\n'
                      '                        i += 1\n'
                      '                p = self.heads[k](z)\n'
                      '            preds.append(p * self.scales[k] if self.ensemble else p)\n'
                      '        pred = preds[0] if len(preds) == 1 else torch.stack(preds).mean(0)\n'
                      '        return (pred, *new)\n'
                      '\n'
                      '\n'
                      'def state_names(net):\n'
                      '    members = list(net.nets) if isinstance(net, EnsembleNet) else [net]\n'
                      '    return [f"m{k}_{s}" for k, m in enumerate(members) for s, _ in _member_states(m)]\n'
                      '\n'
                      '\n'
                      'def export_onnx(net, path: str):\n'
                      '    """Export a model (GRUNet, MinGRUNet, TCNNet) or EnsembleNet as a one-row step graph. '
                      'Inputs: x, x_prev\n'
                      '    (dropped from the graph when no member uses diff features), then the states per member '
                      'named m{k}_<state>\n'
                      '    (h{l} / c{l} for GRU/LSTM and minGRU, b{l} for TCN buffers); outputs: pred, then the new '
                      'states in the same\n'
                      "    order. All states start at zero (solution.py zero-fills them from the graph's input "
                      'shapes)."""\n'
                      '    net = net.eval().cpu()\n'
                      '    feat_kind(net)  # raises if ensemble members need different extra features\n'
                      '    names = state_names(net)\n'
                      '    members = list(net.nets) if isinstance(net, EnsembleNet) else [net]\n'
                      '    states = [torch.zeros(*shape) for m in members for _, shape in _member_states(m)]\n'
                      '    args = (torch.zeros(1, 1, N_FEATURES + needs_extra(net)), torch.zeros(1, N_FEATURES), '
