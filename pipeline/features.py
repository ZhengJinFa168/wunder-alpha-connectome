"""Extra causal input features, computed identically offline (training, whole sequences) and
online (inference, one row at a time):

* activity of each instrument's prices / volumes / trades: mean |x_t - x_{t-1}| over the group
  (0 on the first row of a sequence), now and as EMAs;
* EMAs of the extra features a2..a5 (a3 = the strongest scoring-mask signal).

EMA_k(t) = EMA_k(t-1) + (x_t - EMA_k(t-1)) / span_k, started at x_0. All values standardised with
fixed constants (MEAN / STD, measured once on training data). Width: N_EXTRA = 36.

Feature sets ("kinds"): "act" = the 36 above; "norm" = every one of the 112 inputs as a z-score against its
own running mean and std since the start of the sequence (per-sequence level and scale, causal);
"act+norm" = both, in that order; "grp" = the instrument-group detector's 4 probabilities (below).
A model's kind follows from its input width (kind_for_width).

Instrument groups: every sequence comes from one of 4 instruments, told apart by the tick size of its targets
(TICKS; pipeline/groups.py labels them from the targets). At inference the group is detected from the inputs:
multinomial logistic regression on the mean and std of the 112 inputs over the first DET_ROWS rows (the
never-scored warm-up), constants below (fitted by `python -m pipeline.groups --fit`). The "grp" feature is that
detector applied to the rows seen so far, frozen from row DET_ROWS - 1 on.
This file is copied next to solution.py as wnn_features.py, so it must only need numpy at inference.
"""
import numpy as np

GROUPS = [(0, 22), (22, 44), (44, 52), (52, 74), (74, 96), (96, 104)]  # i0 p, i0 v, i0 trades, i1 p, i1 v, i1 trades
LEVEL_COLS = [106, 107, 108, 109]                                      # a2, a3, a4, a5
SPANS = [20, 200, 2000]
N_EXTRA = len(GROUPS) * (1 + len(SPANS)) + len(LEVEL_COLS) * len(SPANS)  # 36
NORM_FLOOR = 0.02  # added to the running std (inputs are globally standardised), so early rows / flat columns stay finite
NORM_CLIP = 8.0
KINDS = {"act": N_EXTRA, "norm": 112, "act+norm": N_EXTRA + 112, "grp": 4}
TICKS = [0.12543, 0.24133, 0.46854, 0.65687]  # tick size of each group, in target units
DET_ROWS = 99


def width(kind):
    """Number of extra inputs of a feature kind ('' or None = none)."""
    return KINDS[kind] if kind else 0


def kind_for_width(n):
    return next(k for k, w in KINDS.items() if w == n)

