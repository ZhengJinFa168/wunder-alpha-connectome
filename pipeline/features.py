def _raw_offline(X):
    """X [B,T,112] float32 -> unstandardised extras [B,T,36] float64 (whole sequences, exact EMA)."""
    from scipy.signal import lfilter

    X = X.astype(np.float64)
    d = np.abs(np.diff(X, axis=1, prepend=X[:, :1]))
    act = np.stack([d[..., a:b].mean(-1) for a, b in GROUPS], -1)      # [B,T,6]
    lev = X[..., LEVEL_COLS]                                           # [B,T,4]
    out = [act]
    for v in (act, lev):
        for span in SPANS:
            a = 1.0 / span
            zi = (1 - a) * v[:, :1]                                     # [B,1,F]: so that EMA(0) = x_0
            y, _ = lfilter([a], [1, -(1 - a)], v, axis=1, zi=zi)
            out.append(y)
    # order: act, act_ema20, act_ema200, act_ema2000, lev_ema20, lev_ema200, lev_ema2000
    return np.concatenate(out, -1)


def _norm_offline(X):
    """X [B,T,112] -> running z-scores [B,T,112] float64. Values are taken relative to the first row, so the
    float64 running sums stay exact enough; the online version adds them up in the same order."""
    xs = X.astype(np.float64)
    xs -= xs[:, :1]
    n = np.arange(1, X.shape[1] + 1, dtype=np.float64)[None, :, None]
    mean = np.cumsum(xs, 1) / n
    var = np.maximum(np.cumsum(xs * xs, 1) / n - mean * mean, 0.0)
    return np.clip((xs - mean) / np.sqrt(var + NORM_FLOOR ** 2), -NORM_CLIP, NORM_CLIP)


def offline(X, kind="act", chunk=16):
    """Extras [B,T,width(kind)] float32 for whole sequences. Computed `chunk` sequences at a time:
    the float64 intermediates of a whole 256-sequence batch would need ~10 GB of RAM."""
    out = np.empty(X.shape[:2] + (width(kind),), np.float32)
    for i in range(0, len(X), chunk):
        x = X[i:i + chunk]
        out[i:i + chunk] = np.concatenate([_OFFLINE[part](x) for part in kind.split("+")], -1)
    return out


def _det_probs(mean, std):
    """Detector: [..., 112] mean and std -> [..., 4] group probabilities."""
    z = np.clip((np.concatenate([mean, std], -1) - DET_MEAN) / DET_SCALE, -10, 10)
    logits = z @ np.asarray(DET_COEF).T + DET_INTERCEPT
    e = np.exp(logits - logits.max(-1, keepdims=True))
    return e / e.sum(-1, keepdims=True)


def _grp_offline(X):
    """X [B,T,112] -> [B,T,4]: detector on rows 0..t (frozen from row DET_ROWS - 1 on). Sums are taken relative
    to the first row (exact enough in float64), in the same order as _GrpOnline."""
    n_rows = min(DET_ROWS, X.shape[1])
    x0 = X[:, :1].astype(np.float64)
    xs = X[:, :n_rows].astype(np.float64) - x0
    n = np.arange(1, n_rows + 1, dtype=np.float64)[None, :, None]
    m = np.cumsum(xs, 1) / n
    std = np.sqrt(np.maximum(np.cumsum(xs * xs, 1) / n - m * m, 0.0))
    p = _det_probs(m + x0, std)
    return np.concatenate([p, np.repeat(p[:, -1:], X.shape[1] - n_rows, 1)], 1)


def detect(X):
    """Group probabilities [B,4] of whole sequences X [B,T>=DET_ROWS,112] (what the online detector has after the
    warm-up)."""
    return _grp_offline(X[:, :DET_ROWS, :112])[:, -1]


_OFFLINE = {"act": lambda x: (_raw_offline(x) - MEAN) / STD, "norm": _norm_offline, "grp": _grp_offline}


class Online:
    """Row-by-row version of `offline(X, kind)`; reset() at every new sequence."""

    def __init__(self, kind="act"):
        self.parts = [{"act": _ActOnline, "norm": _NormOnline, "grp": _GrpOnline}[p]() for p in kind.split("+")]

    def reset(self):
        for p in self.parts:
            p.reset()

    def __call__(self, x):
        if len(self.parts) == 1:
            return self.parts[0](x)
        return np.concatenate([p(x) for p in self.parts])


class _NormOnline:
    def __init__(self):
        self.reset()

    def reset(self):
        self.x0 = None

    def __call__(self, x):
        xs = np.asarray(x, dtype=np.float64)
        if self.x0 is None:
            self.x0, self.n = xs.copy(), 0
            self.s1, self.s2 = np.zeros_like(xs), np.zeros_like(xs)
        xs = xs - self.x0
        self.n += 1
        self.s1 += xs
        self.s2 += xs * xs
        mean = self.s1 / self.n
        var = np.maximum(self.s2 / self.n - mean * mean, 0.0)
        return np.clip((xs - mean) / np.sqrt(var + NORM_FLOOR ** 2), -NORM_CLIP, NORM_CLIP).astype(np.float32)


class _GrpOnline:
    def __init__(self):
        self.reset()

    def reset(self):
        self.x0, self.p = None, None

    def __call__(self, x):
        if self.p is not None and self.n >= DET_ROWS:
            return self.p
        xs = np.asarray(x, dtype=np.float64)
        if self.x0 is None:
            self.x0, self.n = xs.copy(), 0
            self.s1, self.s2 = np.zeros_like(xs), np.zeros_like(xs)
        xs = xs - self.x0
        self.n += 1
        self.s1 += xs
        self.s2 += xs * xs
        m = self.s1 / self.n
        std = np.sqrt(np.maximum(self.s2 / self.n - m * m, 0.0))
        self.p = _det_probs(m + self.x0, std).astype(np.float32)
        return self.p


class _ActOnline:
    """Row-by-row "act" features. Kept to a handful of numpy calls per row: one matrix product for all group
    activities, one array for all EMAs."""

    def __init__(self):
        n_g, n_l = len(GROUPS), len(LEVEL_COLS)
        self.G = np.zeros((112, n_g))                                   # |dx| @ G = per-group mean
        for k, (a, b) in enumerate(GROUPS):
            self.G[a:b, k] = 1.0 / (b - a)
        self.alpha = np.array([1.0 / s for s in SPANS])[:, None]       # [3,1]
        self.mean = np.asarray(MEAN, dtype=np.float64)
        self.inv_std = 1.0 / np.asarray(STD, dtype=np.float64)
        self.n_g = n_g
        self.raw = np.empty(N_EXTRA)
        self.lev_idx = np.array(LEVEL_COLS)
        self.reset()

    def reset(self):
        self.prev = None

    def __call__(self, x):
        x = np.asarray(x, dtype=np.float64)
        n_g = self.n_g
        if self.prev is None:
            act = np.zeros(n_g)
            self.ema = np.empty((len(SPANS), n_g + len(LEVEL_COLS)))     # [3, 6 activities + 4 levels]
            self.ema[:, :n_g] = 0.0
            self.ema[:, n_g:] = x[self.lev_idx]
        else:
            act = np.abs(x - self.prev) @ self.G
            v = np.concatenate((act, x[self.lev_idx]))
            self.ema += (v - self.ema) * self.alpha
        self.prev = x
        raw = self.raw
        raw[:n_g] = act
        raw[n_g:n_g * 4] = self.ema[:, :n_g].ravel()
        raw[n_g * 4:] = self.ema[:, n_g:].ravel()
        return ((raw - self.mean) * self.inv_std).astype(np.float32)


